#!/usr/bin/env python3
"""Upload completed FBX/GLB exports to Lightek Studio using a watcher token."""
import argparse
import hashlib
import http.client
import json
import logging
import os
from pathlib import Path
import re
import sqlite3
import sys
import time
from urllib.parse import urlsplit
import uuid

EXTENSIONS = {".fbx", ".glb"}
MAX_BYTES = 150 * 1024 * 1024
LOG = logging.getLogger("sync_exports")


class AuthExpired(Exception):
    pass


class UploadRejected(Exception):
    pass


def file_version(info):
    return (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns)


def endpoint(value):
    url = urlsplit(value)
    if (url.scheme not in {"http", "https"} or not url.hostname or url.username or url.password
            or url.query or url.fragment or url.path != "/api/v1/assets/ingest"):
        raise ValueError("Use the ingest URL generated by Pipeline Hub")
    if url.scheme == "http" and url.hostname not in {"localhost", "127.0.0.1", "::1"}:
        raise ValueError("The watcher requires HTTPS outside localhost")
    return url


def upload(url, token, source, name, size):
    boundary = uuid.uuid4().hex
    # The server associates the attachment name with the card. Keep valid
    # filenames, and strip characters that can break multipart headers.
    safe_name = re.sub(r'[\x00-\x1f\x7f"\\/]', "_", name)
    prefix = (
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"file\"; filename=\"{safe_name}\"\r\n"
        "Content-Type: application/octet-stream\r\n\r\n"
    ).encode()
    suffix = f"\r\n--{boundary}--\r\n".encode()
    factory = http.client.HTTPSConnection if url.scheme == "https" else http.client.HTTPConnection
    connection = factory(url.hostname, url.port, timeout=45)
    try:
        connection.putrequest("POST", url.path)
        connection.putheader("Authorization", f"Bearer {token}")
        connection.putheader("Accept", "application/json")
        connection.putheader("Content-Type", f"multipart/form-data; boundary={boundary}")
        connection.putheader("Content-Length", str(len(prefix) + size + len(suffix)))
        connection.endheaders()
        connection.send(prefix)
        remaining = size
        while remaining:
            chunk = source.read(min(1024 * 1024, remaining))
            if not chunk:
                raise OSError("File changed while sending")
            connection.send(chunk)
            remaining -= len(chunk)
        connection.send(suffix)
        response = connection.getresponse()
        raw = response.read(65536)
        try:
            data = json.loads(raw)
        except (ValueError, TypeError):
            data = {}
        detail = data.get("error") if isinstance(data, dict) else None
        if response.status == 202 and isinstance(data, dict) and type(data.get("id")) is int:
            return data["id"]
        if response.status in (401, 403) or 300 <= response.status < 400:
            raise AuthExpired(detail or f"Studio rejected the watcher token ({response.status})")
        if response.status == 429 or response.status >= 500:
            raise OSError(detail or f"Studio returned HTTP {response.status}")
        raise UploadRejected(detail or f"Studio rejected the file (HTTP {response.status})")
    finally:
        connection.close()


def watch(args, url, token, db):
    observed = {}
    retry = {}
    rejected = set()
    handled = set()
    scope = args.url + ":" + (args.scope or hashlib.sha256(token.encode()).hexdigest())
    if args.once:
        source_entries = args.folder.rglob("*") if args.recursive else args.folder.iterdir()
        candidates = [path for path in source_entries if path.suffix.lower() in EXTENSIONS and path.is_file() and not path.is_symlink()]
        if not candidates:
            return 0
        for path in candidates:
            observed[path] = (file_version(path.stat()), time.monotonic())
        time.sleep(args.settle)

    while True:
        failures = 0
        current = set()
        paths = args.folder.rglob("*") if args.recursive else args.folder.iterdir()
        for path in paths:
            if path.suffix.lower() not in EXTENSIONS or path.is_symlink() or not path.is_file():
                continue
            if args.once and path not in observed:
                continue
            try:
                version = file_version(path.stat())
                current.add(path)
                state, since = observed.get(path, (None, 0))
                now = time.monotonic()
                if version != state:
                    observed[path] = (version, now)
                    if args.once:
                        raise OSError("File changed during settle interval")
                    continue
                if now - since < args.settle:
                    continue
                if (path, version) in rejected or (path, version) in handled:
                    continue
                count, due = retry.get((path, version), (0, 0))
                if due > now:
                    continue
                if not 0 < version[2] <= MAX_BYTES:
                    raise UploadRejected("Expected a nonempty export no larger than 150 MB")

                with path.open("rb") as source:
                    digest = hashlib.sha256()
                    while chunk := source.read(1024 * 1024):
                        digest.update(chunk)
                    if file_version(os.fstat(source.fileno())) != version or file_version(path.stat()) != version:
                        raise OSError("File changed while hashing")
                    key = path.suffix.lower() + ":" + digest.hexdigest()
                    if db.execute("SELECT 1 FROM uploads WHERE scope=? AND digest=?", (scope, key)).fetchone():
                        handled.add((path, version))
                        continue
                    source.seek(0)
                    asset_id = upload(url, token, source, path.name, version[2])
                db.execute("INSERT OR IGNORE INTO uploads VALUES (?, ?, ?)", (scope, key, asset_id))
                db.commit()
                handled.add((path, version))
                retry.pop((path, version), None)
                LOG.info("%s accepted as Studio asset #%d", path, asset_id)
            except UploadRejected as error:
                LOG.error("%s: %s", path, error)
                rejected.add((path, version))
                failures += 1
            except (OSError, http.client.HTTPException) as error:
                LOG.warning("%s: %s", path, error)
                if path in current:
                    count = retry.get((path, version), (0, 0))[0]
                    retry[(path, version)] = (count + 1, time.monotonic() + min(300, 2 ** min(count + 1, 8)))
                failures += 1
        if args.once:
            return int(bool(failures))
        observed = {path: state for path, state in observed.items() if path in current}
        retry = {key: state for key, state in retry.items() if key[0] in observed and key[1] == observed[key[0]][0]}
        rejected = {key for key in rejected if key[0] in observed and key[1] == observed[key[0]][0]}
        handled = {key for key in handled if key[0] in observed and key[1] == observed[key[0]][0]}
        time.sleep(args.interval)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("folder", type=Path)
    parser.add_argument("--url", required=True)
    parser.add_argument("--scope", help="Workspace key shown by Pipeline Hub, stable across token rotations")
    parser.add_argument("--state", type=Path, default=Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state")) /
                        "lightek-studio" / "watcher.sqlite3")
    parser.add_argument("--settle", type=float, default=5, help="Seconds an export must remain unchanged")
    parser.add_argument("--interval", type=float, default=3)
    parser.add_argument("--recursive", action="store_true")
    parser.add_argument("--once", action="store_true", help="Wait for stability, then run one upload pass")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    token = os.environ.get("LIGHTEK_INGEST_TOKEN", "").strip()
    try:
        if not re.fullmatch(r"\S{1,4096}", token):
            raise ValueError("Set LIGHTEK_INGEST_TOKEN to the token from Pipeline Hub")
        if not args.folder.is_dir() or not 0.1 <= args.settle <= 120 or not 0.1 <= args.interval <= 120:
            raise ValueError("Choose an export directory and intervals between 0.1 and 120 seconds")
        url = endpoint(args.url)
        os.umask(0o077)
        args.state.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        with sqlite3.connect(args.state, timeout=15) as database:
            database.execute("CREATE TABLE IF NOT EXISTS uploads (scope TEXT, digest TEXT, asset INTEGER, PRIMARY KEY (scope, digest))")
            LOG.info("Watching %s", args.folder)
            return watch(args, url, token, database)
    except (AuthExpired, ValueError, OSError, sqlite3.Error) as error:
        LOG.error("%s", error)
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
